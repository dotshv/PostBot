def t(key: str, locale: str = "en", **kwargs) -> str:
    lang_dict = STRINGS.get(locale, STRINGS.get("en", {}))
    template = lang_dict.get(key, STRINGS.get("en", {}).get(key, f"[{key}]"))
    try:
        return template.format(**kwargs)
    except Exception:
        return template

def get_button_variants(key: str, extra: list = None) -> set:
    variants = set()
    if extra:
        for x in extra:
            variants.add(x.lower())
    for lang_dict in STRINGS.values():
        val = lang_dict.get(key)
        if val:
            variants.add(val.lower())
    return variants
